        // load data 
        public void LoadData()
        {
            // This line of code is generated by Data Source Configuration Wizard
            this.entityInstantFeedbackSource1.GetQueryable += entityInstantFeedbackSource1_GetQueryable;
            // This line of code is generated by Data Source Configuration Wizard
            this.entityInstantFeedbackSource1.DismissQueryable += entityInstantFeedbackSource1_DismissQueryable;
            this.entityInstantFeedbackSource1.Refresh();

            clearText();
            btn_add.Enabled = true;
            btn_edit.Enabled = true;
            btn_delete.Enabled = false;
            btn_save.Enabled = false;
        }


        void enableTexts(bool enable)
        {
            // Enable Texts Boxes
            foreach (var text in layoutControl3.Controls)
            {
                if (text is TextEdit)
                {
                    (text as TextEdit).Enabled = enable;
                }
            }

            chk_is_stop.Enabled = enable;

        }

        void clearText()
        {
            foreach (var text in layoutControl3.Controls)
            {
                if (text is TextEdit)
                {
                    (text as TextEdit).Text = string.Empty;
                }
            }

            enableTexts(false);
        }



        private void btn_add_Click(object sender, EventArgs e)
        {

            enableTexts(true);

            // focus 1st text box
            txt_ssn_name.Focus();

            btn_save.Enabled = true;
            btn_return.Enabled = true;

        }

        private void btn_save_Click(object sender, EventArgs e)
        {
            // Enable Texts Boxes
            foreach (var item in layoutControl3.Controls)
            {
                if (item is TextEdit)
                {
                    if (((TextEdit)item).Text == String.Empty)
                    {
                        new frm_Notification().ShowAlert("هناك حقل فارغ", frm_Notification.AlertType.Warning);
                        return;
                    }
                }
            }

            // add
            if (id == 0)
            {
                ssn = new tbl_SSN_TypeSet
                {
                    SSN_ArName = txt_ssn_name.Text,
                    SSN_EnName = txt_ssn_en_name.Text,
                    Is_Stop = chk_is_stop.Checked ? true : false,
                };
            }
            else // edit
            {

                ssn = new tbl_SSN_TypeSet
                {
                    Id = id,
                    SSN_ArName = txt_ssn_name.Text,
                    SSN_EnName = txt_ssn_en_name.Text,
                    Is_Stop = chk_is_stop.Checked ? true : false,
                };
            }

            AddOrUpdate(ssn);
        }

        async void AddOrUpdate(tbl_SSN_TypeSet ssn)
        {
            try
            {
                await Task.Run(() => db.tbl_SSN_TypeSet.AddOrUpdate(ssn));
                state = true;
                await db.SaveChangesAsync();

                if (state == true)
                {
                    new frm_Notification().ShowAlert("تمت العملية بنجاح", frm_Notification.AlertType.success);
                    LoadData();
                }
                else
                {
                    new frm_Notification().ShowAlert("هناك مشكلة في في إجراء العملية", frm_Notification.AlertType.Warning);
                }
            }
            catch
            {
                new frm_Notification().ShowAlert(" هناك مشكلة في الإتصال بالسيرفر", frm_Notification.AlertType.Warning);
            }

        }

        private void btn_return_Click(object sender, EventArgs e)
        {
            if (MessageBox.Show("هل تريد التراجع؟ سيتم التغير في القيم الحالية", "", MessageBoxButtons.YesNo, MessageBoxIcon.Question) == DialogResult.Yes)
            {
                var changed = db.ChangeTracker.Entries().Where(x => x.State != EntityState.Unchanged).ToList();
                foreach (var obj in changed)
                {
                    switch (obj.State)
                    {
                        case EntityState.Modified:
                            obj.CurrentValues.SetValues(obj.OriginalValues);
                            obj.State = EntityState.Unchanged;
                            break;
                        case EntityState.Added:
                            obj.State = EntityState.Detached;
                            break;
                        case EntityState.Deleted:
                            obj.State = EntityState.Unchanged;
                            break;
                    }
                }
                LoadData();
            }
        }

