        public ctrl_ItemType()
        {
            InitializeComponent();
            RefreshData();
            table = new tbl_Items_Type();

        }

     
        public override void RefreshData()
        {
            base.RefreshData();
            // This line of code is generated by Data Source Configuration Wizard
            // Instantiate a new DBContext
            Items_Types = new List<tbl_Items_Type>();
            MOHASEB.Model.MOHASEB_DBEntities db = new MOHASEB.Model.MOHASEB_DBEntities();
            // Call the LoadAsync method to asynchronously get the data for the given DbSet from the database.
            db.tbl_Items_Type.LoadAsync().ContinueWith(loadTask =>
            {
                // Bind data to control when loading complete
                sysdiagramsBindingSource.DataSource = db.tbl_Items_Type.Local.ToBindingList();
            }, System.Threading.Tasks.TaskScheduler.FromCurrentSynchronizationContext());
        }

        public override bool IsValidData()
        {
            bool isvalid = false;

            foreach (var item in layoutControl3.Controls)
            {
                if (item is TextEdit)
                {
                    isvalid = (item as TextEdit).ValidatingData();
                }

            }

            if (!isvalid)
                return false;
            else
                return base.IsValidData();
        }

        public override void Save()
        {

            SetData();
          
            if (operation == EntityOperation.Operation.Delete)
            {

                EntityOperation.SqlOperationAsync<tbl_Items_Type>(new tbl_Items_Type { IType_No = id }, EntityOperation.Operation.Delete);
            }
            else
            {
                EntityOperation.SqlOperationAsync<tbl_Items_Type>(table, operation);

            }
            base.Save();
       
        }

        public override void New()
        {
            operation = EntityOperation.Operation.Add;
            txt_type_name.Focus();
            base.New();
        }

        public override void Edit()
        {
            if (table == null)
            {
                new frm_Notification().ShowAlert("لا بيانات لتعديلها", frm_Notification.AlertType.Error);
                return;
            }

            operation = EntityOperation.Operation.Update;
            EnableFields(true);
            base.Edit();
        }

        public override void GetData()
        {
            base.GetData();
            id = Convert.ToInt32(gridView1.GetFocusedRowCellValue("IType_No"));
            txt_type_name.Text = gridView1.GetFocusedRowCellValue("IType_Name").ToString();
           
                  
                chk_is_for_salse.Checked = gridView1.GetFocusedRowCellValue("IType_ForSale").ToString() == "1"?true:false;
     
                chk_is_service.Checked = gridView1.GetFocusedRowCellValue("IType_Service").ToString() == "1" ? true : false;
        }

        public override void SetData()
        {
           
            table = new tbl_Items_Type();
            if (operation == EntityOperation.Operation.Update)
            {

                table.IType_No = id;
              


         
            
            }

            //table.IType_Name = txt_type_name.Text;
            //table.IType_ForSale = chk_is_for_salse.Checked ? true : false;
            //table.IType_Service = chk_is_service.Checked ? true : false;
            base.SetData();
        }


        public override void Delete()
        {
            table = new tbl_Items_Type();
            if (table == null)
            {
                new frm_Notification().ShowAlert("لا بيانات لحذفها", frm_Notification.AlertType.Error);
                return;
            }
            operation = EntityOperation.Operation.Delete;
            base.Delete();
        }


        public override void ClearFields(bool enable)
        {
            base.ClearFields(enable);
            foreach (var text in layoutControl3.Controls)
            {
                if (text is TextEdit)
                {
                    (text as TextEdit).Text = string.Empty;
                }
            }

        }


        public override void EnableFields(bool enable)
        {
            base.EnableFields(enable);
            // Enable Texts Boxes
            foreach (var text in layoutControl3.Controls)
            {
                if (text is TextEdit)
                {
                    (text as TextEdit).Enabled = enable;
                }
            }

            foreach (var text in layoutControl1.Controls)
            {
                if (text is TextEdit)
                {
                    (text as TextEdit).Enabled = enable;
                }
            }

        }
        private void gridView1_DoubleClick(object sender, EventArgs e)
